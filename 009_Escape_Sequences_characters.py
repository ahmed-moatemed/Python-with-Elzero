# --------------------------------------------
# Escape Sequences Characters
# \b => Back Space
# \newline => Escape New Line + \
# \\ => Escape Back Slach
# \' => Escape Single Quotes
# \" => Escape Single Quotes
# \n => Line Feed Character
# \r => Carriage Return
# \t => Horizontal Tab 
# \xhh => Character Hex Value
# ------------------------------


# BAck Space
print("Hello\bWorled")  #Will Remove o

# Escape New Line + \
print("Hello \
I love \
Python")

# Escape Back Slach
print("I Love Back Slach \\")

# Escape Single Quote
print('I Love Single Quote \'Test\' ')

# Escape Double Quotes
print("I Love Double Quotes \"Test\" ")

# Line Feed 
print("Hello World\nSecond Line")

# Carriage Return
print("123456\rABCD") #ABCD56

# Horizontal Tab
print("Hello\tPython")

# Character Hex Value
print("\x4f \x73")