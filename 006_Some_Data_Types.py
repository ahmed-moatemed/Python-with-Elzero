# ----------------------------
# type()
# All Data in Python is Object
# ----------------------------

print(type(10)) # int => Integer
print(type(110)) # int => Integer
print(type(-10)) # int => Integer

print(type(100.9)) # float => Floating Point Number
print(type(1.93434)) # float => Floating Point Number
print(type(-10.9)) # float => Floating Point Number

print(type("Hello Python")) # str => String 

print(type([1,2,3,4])) # list => List 

print(type((1,2,3,4,5))) # tuple => Tuple

print(type({"one": 1, "two": 2})) # dict => Dictionary

print(type(2 == 2)) # bool => Boolean

